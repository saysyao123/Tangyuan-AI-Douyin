def to_native(im,id):
 rgb=im.convert('RGB')
 pal_img=Image.new('P',(1,1));pal_img.putpalette(PALETTE)
 indexed=rgb.quantize(palette=pal_img,dither=Image.Dither.NONE)
 pixels=bytearray(indexed.tobytes())
 alpha=im.getchannel('A').tobytes()
 for i,a in enumerate(alpha):
  if a<120:pixels[i]=255
  elif pixels[i]==255:
   p=im.getpixel((i%im.width,i//im.width))[:3]
   pixels[i]=min(range(255),key=lambda j:sum((standard[j][k]-p[k])**2 for k in range(3)))
 frame=bytearray(struct.pack('<HH',im.width,im.height))
 i=0
 while i<len(pixels):
  on=pixels[i]!=255;j=i
  while j<len(pixels) and j-i<127 and (pixels[j]!=255)==on:j+=1
  frame.append((j-i) if on else (128+j-i))
  if on:frame.extend(pixels[i:j])
  i=j
 chunk=bytearray(struct.pack('<H',1));chunk.extend(frame)
 if len(chunk)%2:chunk.append(0)
 buf=gzip.compress(chunk,mtime=0)
 path=f'assets/generated/sprites/{id}.rle'
 (project/path).write_bytes(buf)
 preview=Image.frombytes('P',im.size,bytes(pixels))
 preview.putpalette(PALETTE)
 preview.save(evidence/f'{id}.png',transparency=255)
 catalog['assets']['sprite.'+id]={'kind':'sprite','path':path,
  'mediaType':'application/vnd.type-pal.rle','bytes':len(buf),
  'sha256':hashlib.sha256(buf).hexdigest(),'origin':{'kind':'generated'},'label':id}
 if not any(x['id']==id for x in sprites):
  sprites.append({'id':id,'label':id,'asset':'sprite.'+id,'layout':{'kind':'static'}})
 made[id]={'dimensions':[im.width,im.height],'bytes':len(buf),'sha256':hashlib.sha256(buf).hexdigest(),
           'opaque':sum(v!=255 for v in pixels)}

