def sprite(w,h):return Image.new('RGBA',(w,h),(0,0,0,0))
def masked_grain(im,pts,base,seed=0,density=.09):
 r=random.Random(seed)
 mask=Image.new('1',im.size,0);ImageDraw.Draw(mask).polygon(pts,fill=1)
 draw=ImageDraw.Draw(im);draw.polygon(pts,fill=base)
 px=mask.load()
 for y in range(max(0,min(y for x,y in pts)),min(im.height,max(y for x,y in pts)+1)):
  for x in range(max(0,min(x for x,y in pts)),min(im.width,max(x for x,y in pts)+1)):
   if px[x,y] and r.random()<density:
    delta=r.choice([-17,-12,-7,7,12,17])
    draw.point((x,y),fill=tuple(min(255,max(0,z+delta)) for z in base))
 return draw

